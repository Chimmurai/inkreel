def reel(n=24):
    """піксельна котушка: диск із п'ятьма отворами й втулкою"""
    import math
    c = (n - 1) / 2
    rows = []
    for y in range(n):
        r = ""
        for x in range(n):
            d = math.hypot(x - c, y - c)
            hole = d < 1.6 or any(math.hypot(x - c - 6.2 * math.cos(a), y - c - 6.2 * math.sin(a)) < 2.4
                                  for a in [i * 2 * math.pi / 5 - math.pi / 2 for i in range(5)])
            r += "#" if (d <= c + 0.2 and not hole) else "."
        rows.append(r)
    return rows


