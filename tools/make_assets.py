def render(rows, scale=1, fg=(0, 0, 0, 255), bg=(0, 0, 0, 0)):
    h, w = len(rows), max(len(r) for r in rows)
    im = Image.new("RGBA", (w, h), bg)
    px = im.load()
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                px[x, y] = fg
    return im.resize((w * scale, h * scale), Image.NEAREST) if scale != 1 else im


def logo(text="InkReel", scale=4, fg=(0, 0, 0, 255)):
    rows = [""] * 7
    for ch in text:
        g = LOGO_FONT[ch]
        for i in range(7):
            rows[i] += g[i] + "."
    return render(rows, scale, fg)


